let current = 'tr';

export function setLocale(locale) {
  current = locale === 'en' ? 'en' : 'tr';
  if (typeof document !== 'undefined') document.documentElement.lang = current;
}

export function getLocale() {
  return current;
}

export function detectLocale() {
  const lang = typeof navigator !== 'undefined' ? navigator.language || '' : '';
  return lang.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export function t(key, vars) {
  let text = STRINGS[current][key] ?? STRINGS.tr[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

/** Test amaçlı: iki dilin anahtar kümesi aynı mı? Farkı döndürür. */
export function missingKeys() {
  const tr = new Set(Object.keys(STRINGS.tr));
  const en = new Set(Object.keys(STRINGS.en));
  return {
    missingInEn: [...tr].filter((k) => !en.has(k)),
    missingInTr: [...en].filter((k) => !tr.has(k)),
  };
}
